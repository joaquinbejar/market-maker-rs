//! Checks `doc/fixtures/avellaneda_stoikov.json` against the Avellaneda Stoikov quoting
//! functions. The file is the same on every target, so this test running on x86_64 and on
//! aarch64 shows the outputs are bit identical across them.
//!
//! Run with `MM_WRITE_AS_FIXTURES=1` to rewrite the file after a deliberate change of the
//! arithmetic, then once more without the variable to check the embedded copy.

use market_maker_rs::Decimal;
use market_maker_rs::dec;
use market_maker_rs::strategy::avellaneda_stoikov::{
    AVELLANEDA_STOIKOV_FIXTURES, LOG_RATIO_SIGNIFICANT_DIGITS, calculate_optimal_quotes,
    calculate_optimal_spread, calculate_reservation_price, log1p_ratio_parts,
};
use serde_json::{Value, json};

const FIXTURE: &str = "doc/fixtures/avellaneda_stoikov.json";

fn outcome<T: ToString>(result: Result<T, market_maker_rs::types::error::MMError>) -> Value {
    match result {
        Ok(v) => Value::String(v.to_string()),
        Err(e) => json!({ "error": format!("{e:?}").split('(').next().unwrap() }),
    }
}

fn case(mid: Decimal, q: Decimal, gamma: Decimal, sigma: Decimal, ms: u64, k: Decimal) -> Value {
    let quotes = calculate_optimal_quotes(mid, q, gamma, sigma, ms, k);
    let (bid, ask) = match &quotes {
        Ok((b, a)) => (Value::String(b.to_string()), Value::String(a.to_string())),
        Err(e) => {
            let err = json!({ "error": format!("{e:?}").split('(').next().unwrap() });
            (err.clone(), err)
        }
    };
    json!({
        "input": {
            "mid_price": mid.to_string(),
            "inventory": q.to_string(),
            "risk_aversion": gamma.to_string(),
            "volatility": sigma.to_string(),
            "time_to_terminal_ms": ms,
            "order_intensity": k.to_string(),
        },
        "expected": {
            "reservation_price": outcome(calculate_reservation_price(mid, q, gamma, sigma, ms)),
            "spread": outcome(calculate_optimal_spread(gamma, sigma, ms, k)),
            "bid": bid,
            "ask": ask,
        }
    })
}

fn fixtures() -> Value {
    let mut cases = Vec::new();
    let mids = [dec!(100), dec!(0.05), dec!(65000.5)];
    let inventories = [dec!(0), dec!(10), dec!(-3.5)];
    let gammas = [dec!(0.1), dec!(1), dec!(0.000001), dec!(0.0000000001)];
    let sigmas = [dec!(0.2), dec!(2.5)];
    let horizons = [0u64, 1, 3_600_000, 86_400_000];
    let intensities = [dec!(1.5), dec!(0.01), dec!(100000)];
    for &mid in &mids {
        for &q in &inventories {
            for &gamma in &gammas {
                for &sigma in &sigmas {
                    for &ms in &horizons {
                        for &k in &intensities {
                            cases.push(case(mid, q, gamma, sigma, ms, k));
                        }
                    }
                }
            }
        }
    }
    // Inputs each function refuses, one per documented refusal.
    let max = Decimal::MAX;
    let errors = [
        (dec!(0), dec!(0), dec!(0.1), dec!(0.2), 3_600_000, dec!(1.5)),
        (dec!(100), dec!(0), dec!(0), dec!(0.2), 3_600_000, dec!(1.5)),
        (dec!(100), dec!(0), dec!(0.1), dec!(0), 3_600_000, dec!(1.5)),
        (dec!(100), dec!(0), dec!(0.1), dec!(0.2), 3_600_000, dec!(0)),
        (
            dec!(100),
            dec!(0),
            dec!(0.1),
            dec!(-0.2),
            3_600_000,
            dec!(-1.5),
        ),
        // gamma / k underflows to zero in Decimal.
        (
            dec!(100),
            dec!(0),
            dec!(0.00000000000000000001),
            dec!(0.2),
            0,
            dec!(10000000000),
        ),
        // sigma squared overflows.
        (dec!(100), dec!(1), dec!(0.1), max, 3_600_000, dec!(1.5)),
        // the inventory and spread terms overflow.
        (
            dec!(1000),
            dec!(200),
            dec!(1),
            dec!(100000000000000),
            u64::MAX,
            dec!(0.3),
        ),
        // gamma / k overflows.
        (dec!(100), dec!(0), max, dec!(0.2), 0, dec!(0.0000000001)),
        // bid not positive.
        (
            dec!(0.5),
            dec!(-1000),
            dec!(1),
            dec!(1),
            36_000_000,
            dec!(0.1),
        ),
    ];
    for (mid, q, gamma, sigma, ms, k) in errors {
        cases.push(case(mid, q, gamma, sigma, ms, k));
    }
    json!({
        "format": 2,
        "about": "Fixtures of the Avellaneda Stoikov quotes: a grid of inputs with the expected reservation price, spread, bid and ask as decimal strings, or the error kind, and a table of the log ratio log1p(x) / x with its unrounded f64 bits and its rounded value. Identical on every target. Generated by tests/avellaneda_stoikov_golden.rs.",
        "log_ratio_significant_digits": LOG_RATIO_SIGNIFICANT_DIGITS,
        "cases": cases,
        "log_ratio": log_ratio_rows(),
    })
}

/// `log1p(x) / x` over log spaced `x` from 1e-20 to 1e20 (five per decade), and the
/// neighbourhoods of `sqrt(2) - 1` and `2^-29`, where `log1p` switches between code paths.
fn log_ratio_rows() -> Value {
    // 10^(i/5) for i in 0..5, to six significant digits, so no float power is needed.
    let steps = [
        dec!(1),
        dec!(1.58489),
        dec!(2.51189),
        dec!(3.98107),
        dec!(6.30957),
    ];
    let mut xs = Vec::new();
    for exponent in -20i32..20 {
        let scale = if exponent < 0 {
            Decimal::ONE / Decimal::from(10i128.pow((-exponent) as u32))
        } else {
            Decimal::from(10i128.pow(exponent as u32))
        };
        for step in steps {
            xs.push(step * scale);
        }
    }
    xs.push(dec!(100000000000000000000));
    let centers = [
        dec!(0.4142135623730950488016887242),     // sqrt(2) - 1
        Decimal::ONE / Decimal::from(1u64 << 29), // 2^-29, rounded to 28 places
    ];
    let offsets = [
        dec!(0),
        dec!(0.000000000000000001),
        dec!(0.000000000000001),
        dec!(0.000000000001),
        dec!(0.000000001),
        dec!(0.000001),
    ];
    for center in centers {
        for offset in offsets {
            let scaled = offset * center;
            xs.push(center + scaled);
            if !offset.is_zero() {
                xs.push(center - scaled);
            }
        }
    }
    let rows: Vec<Value> = xs
        .into_iter()
        .map(|x| {
            let (ratio, rounded) = log1p_ratio_parts(x).unwrap();
            json!({
                "x": x.to_string(),
                "ratio_f64_bits": format!("{:016x}", ratio.to_bits()),
                "rounded": rounded.to_string(),
            })
        })
        .collect();
    Value::Array(rows)
}

#[test]
fn test_avellaneda_stoikov_fixtures_match() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(FIXTURE);
    let generated = fixtures();
    let write = std::env::var_os("MM_WRITE_AS_FIXTURES").is_some();
    if write {
        let mut text = serde_json::to_string_pretty(&generated).unwrap();
        text.push('\n');
        std::fs::write(&path, text).unwrap();
    }
    let text = std::fs::read_to_string(&path).unwrap();
    if !write {
        assert_eq!(
            text, AVELLANEDA_STOIKOV_FIXTURES,
            "rebuild to embed the rewritten {FIXTURE}"
        );
    }
    let published: Value = serde_json::from_str(&text).unwrap();
    assert_eq!(published, generated, "{FIXTURE} is out of date");
}
